"""
Train the road-event classifier and export it as C for the ESP32.

    python ml/train.py                       # real data in data/raw
    python ml/train.py --data data/synthetic # simulator data (placeholder model)

Steps
  1. dataset.py detects events in every session with the firmware's own
     C detector and computes the firmware's own C features.
  2. Candidate models (decision trees, random forests, extra-trees) are
     compared with cross-validation GROUPED BY SESSION, so events from the
     same drive never sit in both train and test (that leak is what made
     the old 100 % accuracy numbers meaningless).
  3. The best model (macro-F1, smaller model wins ties) is refit on all
     data and written to components/pothole_model/include/pothole_model.h,
     which all three firmware projects compile in. Leaf probabilities are
     quantised to uint8 (~4 KB - 40 KB of flash).
"""

import argparse
import datetime
import os

import numpy as np
from sklearn.ensemble import ExtraTreesClassifier, RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix, f1_score
from sklearn.model_selection import StratifiedGroupKFold, StratifiedKFold, cross_val_predict
from sklearn.tree import DecisionTreeClassifier

import dataset
import road_event as re

ROOT = re.ROOT
CLASS_NAMES = dataset.LABELS
HEADER = os.path.join(ROOT, "components", "pothole_model", "include", "pothole_model.h")
REPORT = os.path.join(ROOT, "model", "report.md")
SEED = 42


def candidates():
    models = {}

    for depth in (3, 4, 5, 6, 8):
        models[f"tree_d{depth}"] = DecisionTreeClassifier(
            max_depth=depth, min_samples_leaf=2, class_weight="balanced", random_state=SEED)

    for n in (10, 25):
        for depth in (4, 6, 8):
            models[f"forest_n{n}_d{depth}"] = RandomForestClassifier(
                n_estimators=n, max_depth=depth, min_samples_leaf=2,
                class_weight="balanced", random_state=SEED, n_jobs=-1)
            models[f"extra_n{n}_d{depth}"] = ExtraTreesClassifier(
                n_estimators=n, max_depth=depth, min_samples_leaf=2,
                class_weight="balanced", random_state=SEED, n_jobs=-1)

    return models


def trees_of(model):
    return list(model.estimators_) if hasattr(model, "estimators_") else [model]


def node_count(model):
    return sum(t.tree_.node_count for t in trees_of(model))


def make_cv(y, groups):
    counts = [np.sum(y == c) for c in np.unique(y)]
    groups_per_class = [len(np.unique(groups[y == c])) for c in np.unique(y)]
    k = int(min(5, min(counts)))

    if min(groups_per_class) >= 3:
        k = int(min(k, min(groups_per_class)))
        return StratifiedGroupKFold(n_splits=k, shuffle=True, random_state=SEED), "session-grouped"

    return StratifiedKFold(n_splits=max(k, 2), shuffle=True, random_state=SEED), \
        "NOT grouped (fewer than 3 sessions per class - scores are optimistic)"


# ============================================================
# C EXPORT
# ============================================================

def export_header(model, path, info):
    nodes = []
    roots = []

    for est in trees_of(model):
        t = est.tree_
        base = len(nodes)
        roots.append(base)

        # leaf value columns follow model.classes_ (alphabetical); re-order
        # them to CLASS_NAMES so CLASS_NORMAL/SPEED_HUMP/POTHOLE line up
        order = [list(model.classes_).index(c) if c in model.classes_ else None for c in CLASS_NAMES]

        for i in range(t.node_count):
            if t.children_left[i] == -1:
                v = t.value[i][0]
                p = v / v.sum()
                q = [int(round(p[j] * 255)) if j is not None else 0 for j in order]
                nodes.append((-1, -1, 0, 0.0, q))
            else:
                nodes.append((base + t.children_left[i], base + t.children_right[i],
                              int(t.feature[i]), float(t.threshold[i]), [0, 0, 0]))

    if len(nodes) > 32767:
        raise ValueError("model too large for int16 node indices; reduce trees/depth")

    lines = []
    for left, right, feat, thr, q in nodes:
        lines.append(f"    {{ {left:6d}, {right:6d}, {feat:2d}, {thr: .8e}f, {{ {q[0]:3d}, {q[1]:3d}, {q[2]:3d} }} }},")

    feature_doc = "\n".join(f" *   {i:2d}  {n}" for i, n in enumerate(re.FEATURE_NAMES))
    synthetic = 1 if info["synthetic"] else 0

    text = f"""/*
 * AUTO-GENERATED by ml/train.py - DO NOT EDIT.
 *
 * Model       : {info['name']} ({len(roots)} tree(s), {len(nodes)} nodes, ~{len(nodes) * 12} bytes)
 * Trained     : {info['date']}
 * Data        : {info['data']}
 * Events      : {info['counts']}
 * CV macro-F1 : {info['f1']:.3f} ({info['cv']})
 * Synthetic   : {'YES - placeholder, retrain with real data!' if synthetic else 'no'}
 *
 * Features (computed by components/road_event/road_event.c):
{feature_doc}
 */

#ifndef POTHOLE_MODEL_H
#define POTHOLE_MODEL_H

#include <stdint.h>
#include "road_event.h"

#define CLASS_NORMAL        0
#define CLASS_SPEED_HUMP    1
#define CLASS_POTHOLE       2
#define MODEL_NUM_CLASSES   3
#define MODEL_NUM_FEATURES  {re.NUM_FEATURES}
#define MODEL_NUM_TREES     {len(roots)}
#define MODEL_IS_SYNTHETIC  {synthetic}
#define MODEL_NAME          "{info['name']}"

_Static_assert(MODEL_NUM_FEATURES == RE_NUM_FEATURES,
               "features changed since training - run python ml/train.py");

typedef struct
{{
    int16_t left;           /* -1 for a leaf          */
    int16_t right;
    uint8_t feature;
    float threshold;        /* go left if f <= thr    */
    uint8_t prob[MODEL_NUM_CLASSES];   /* leaf class probability * 255 */
}} model_node_t;

static const int16_t MODEL_ROOTS[MODEL_NUM_TREES] = {{ {", ".join(str(r) for r in roots)} }};

static const model_node_t MODEL_NODES[{len(nodes)}] = {{
{chr(10).join(lines)}
}};

/* Fills proba[MODEL_NUM_CLASSES] (sums to 1) and returns the best class. */
static inline int pothole_predict_proba(const float *f, float *proba)
{{
    uint32_t acc[MODEL_NUM_CLASSES] = {{ 0 }};

    for (int t = 0; t < MODEL_NUM_TREES; t++)
    {{
        int n = MODEL_ROOTS[t];

        while (MODEL_NODES[n].left >= 0)
        {{
            n = (f[MODEL_NODES[n].feature] <= MODEL_NODES[n].threshold)
                ? MODEL_NODES[n].left
                : MODEL_NODES[n].right;
        }}

        for (int c = 0; c < MODEL_NUM_CLASSES; c++)
        {{
            acc[c] += MODEL_NODES[n].prob[c];
        }}
    }}

    uint32_t total = 0;
    int best = 0;

    for (int c = 0; c < MODEL_NUM_CLASSES; c++)
    {{
        total += acc[c];
        if (acc[c] > acc[best]) best = c;
    }}

    for (int c = 0; c < MODEL_NUM_CLASSES; c++)
    {{
        proba[c] = total ? (float)acc[c] / (float)total : 0.0f;
    }}

    return best;
}}

static inline int pothole_predict(const float *f)
{{
    float proba[MODEL_NUM_CLASSES];
    return pothole_predict_proba(f, proba);
}}

#endif
"""

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)

    return nodes, roots


def c_predict(nodes, roots, x):
    """Python mirror of the exported C predictor (float32 compare, uint8 probs)."""
    acc = np.zeros(3)
    xf = np.float32(x)
    for r in roots:
        n = r
        while nodes[n][0] >= 0:
            n = nodes[n][0] if xf[nodes[n][2]] <= np.float32(nodes[n][3]) else nodes[n][1]
        acc += nodes[n][4]
    return int(np.argmax(acc))


# ============================================================
# MAIN
# ============================================================

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", nargs="+", default=[os.path.join(ROOT, "data", "raw")])
    ap.add_argument("--header", default=HEADER)
    ap.add_argument("--report", default=REPORT)
    args = ap.parse_args()

    print("\nLoading sessions")
    X, y, groups, _ = dataset.build(args.data)

    if len(X) == 0:
        raise SystemExit("No events found. Record data first: python ml/collect.py --label pothole")

    counts = {c: int(np.sum(y == c)) for c in CLASS_NAMES}
    print(f"\nEvents: {counts}  sessions: {len(np.unique(groups))}")

    missing = [c for c, n in counts.items() if n < 2]
    if missing:
        raise SystemExit(f"Need at least 2 events of every class; missing: {missing}")

    cv, cv_kind = make_cv(y, groups)
    print(f"Cross-validation: {cv.get_n_splits()} folds, {cv_kind}\n")

    results = []
    for name, model in candidates().items():
        pred = cross_val_predict(model, X, y, groups=groups, cv=cv)
        f1 = f1_score(y, pred, average="macro")
        model.fit(X, y)
        results.append((name, f1, node_count(model), pred))
        print(f"  {name:18s} macro-F1 {f1:.3f}   nodes {node_count(model):5d}")

    best_f1 = max(r[1] for r in results)
    # prefer the smallest model within 0.01 of the best score
    name, f1, _, pred = min((r for r in results if r[1] >= best_f1 - 0.01), key=lambda r: r[2])

    model = candidates()[name]
    model.fit(X, y)

    print(f"\nSelected: {name}  (CV macro-F1 {f1:.3f})\n")
    report = classification_report(y, pred, labels=CLASS_NAMES, zero_division=0)
    cm = confusion_matrix(y, pred, labels=CLASS_NAMES)
    print(report)
    print("Confusion matrix (rows = truth, cols = predicted):", CLASS_NAMES)
    print(cm)

    importance = model.feature_importances_
    order = np.argsort(importance)[::-1]

    info = {
        "name": name,
        "date": datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "data": ", ".join(os.path.relpath(d, ROOT) for d in args.data),
        "counts": counts,
        "f1": f1,
        "cv": cv_kind,
        "synthetic": any("synthetic" in d for d in args.data),
    }

    nodes, roots = export_header(model, args.header, info)

    # verify the C export reproduces sklearn
    agree = np.mean([CLASS_NAMES[c_predict(nodes, roots, x)] == p for x, p in zip(X, model.predict(X))])
    print(f"\nC export agrees with sklearn on {agree * 100:.1f}% of events")

    os.makedirs(os.path.dirname(args.report), exist_ok=True)
    with open(args.report, "w") as fh:
        fh.write(f"# Model report\n\nGenerated by `ml/train.py` on {info['date']}.\n\n")
        if info["synthetic"]:
            fh.write("> **Synthetic data only.** This model is a placeholder that proves the pipeline works. "
                     "Collect real drives and retrain (see docs/03-data-collection.md).\n\n")
        fh.write(f"- Data: `{info['data']}`\n- Events per class: {counts}\n"
                 f"- Sessions: {len(np.unique(groups))}\n- Cross-validation: {cv.get_n_splits()} folds, {cv_kind}\n"
                 f"- Selected model: **{name}**, {len(roots)} tree(s), {len(nodes)} nodes (~{len(nodes) * 12} B flash)\n"
                 f"- C export agreement with scikit-learn: {agree * 100:.1f}%\n\n")
        fh.write("## Candidates\n\n| model | CV macro-F1 | nodes |\n|---|---|---|\n")
        for n, s, size, _ in sorted(results, key=lambda r: -r[1]):
            fh.write(f"| {n} | {s:.3f} | {size} |\n")
        fh.write(f"\n## Cross-validated report ({name})\n\n```\n{report}\n```\n\n")
        fh.write("## Confusion matrix\n\nRows = truth, columns = predicted.\n\n| | " + " | ".join(CLASS_NAMES) + " |\n|---|---|---|---|\n")
        for c, row in zip(CLASS_NAMES, cm):
            fh.write(f"| **{c}** | " + " | ".join(str(v) for v in row) + " |\n")
        fh.write("\n## Feature importance\n\n| feature | importance |\n|---|---|\n")
        for i in order:
            if importance[i] > 0:
                fh.write(f"| {re.FEATURE_NAMES[i]} | {importance[i]:.3f} |\n")

    print(f"\nWrote {os.path.relpath(args.header, ROOT)}")
    print(f"Wrote {os.path.relpath(args.report, ROOT)}")
    print("Rebuild + flash the firmware to deploy (docs/02-firmware.md).")


if __name__ == "__main__":
    main()
